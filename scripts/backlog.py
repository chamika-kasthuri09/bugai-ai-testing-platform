"""Render backlog views from the authoritative JSON; --check never writes."""

import argparse
import csv
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def validate(data):
    tasks = data["tasks"] + data["pilot"]
    indexed = {task["ID"]: task for task in tasks}
    if len(indexed) != len(tasks):
        raise ValueError("Duplicate task ID")
    phases = {phase["no"] for phase in data["phases"]}
    for phase in data["phases"]:
        if any(parent not in phases or parent >= phase["no"] for parent in phase["depends"]):
            raise ValueError("Invalid phase dependency")
    visiting, visited = set(), set()

    def visit(task_id):
        if task_id not in indexed:
            raise ValueError(f"Unknown task dependency: {task_id}")
        if task_id in visiting:
            raise ValueError(f"Task dependency cycle: {task_id}")
        if task_id in visited:
            return
        visiting.add(task_id)
        task = indexed[task_id]
        if task["Status"] not in {"Not started", "In progress", "Done"}:
            raise ValueError(f"Invalid status: {task_id}")
        if task["Status"] == "Done" and not task["Evidence link"]:
            raise ValueError(f"Missing completion evidence: {task_id}")
        estimate = task["Estimate hours"]
        if estimate is not None and (isinstance(estimate, bool) or estimate <= 0):
            raise ValueError(f"Invalid estimate: {task_id}")
        for dependency in task["Depends on tasks"]:
            visit(dependency)
        visiting.remove(task_id)
        visited.add(task_id)

    for task in tasks:
        visit(task["ID"])
    pilot_ids = {task["ID"] for task in data["pilot"]}
    for task in data["pilot"]:
        if task["Estimate hours"] is None or not task["Owner"]:
            raise ValueError("Pilot tasks require provisional estimates and an owner role")
        if any(dep not in pilot_ids for dep in task["Depends on tasks"]):
            raise ValueError("Pilot depends on unscoped full-MVP work")
    for task in data["tasks"]:
        phase_no = int(task["Phase"].split(" - ")[0])
        phase = next(p for p in data["phases"] if p["no"] == phase_no)
        expected = ", ".join(f"{x:02}" for x in phase["depends"]) or "None"
        if task["Depends on phases"] != expected:
            raise ValueError(f"Phase dependency drift: {task['ID']}")
        if task["Window"] != phase["window"] or task["Scope"] != phase["scope"]:
            raise ValueError(f"Phase metadata drift: {task['ID']}")


def csv_view(data):
    output = io.StringIO(newline="")
    writer = csv.DictWriter(output, fieldnames=list(data["tasks"][0]), lineterminator="\n")
    writer.writeheader()
    for task in data["pilot"] + data["tasks"]:
        row = dict(task)
        row["Depends on tasks"] = ", ".join(row["Depends on tasks"]) or "None"
        writer.writerow(row)
    return output.getvalue()


def backlog_view(data):
    lines = ["## 5. Full implementation backlog", "",
             "Generated by `scripts/backlog.py` from `BUGAI_BACKLOG.json`; edit the JSON only.", "",
             "These are full-product work items, not the first-release commitment. The smaller pilot is in Section 12.", "",
             "Phase dependencies describe full phase gates. Task dependencies describe implementation order. Unestimated full-product work has no delivery date.", ""]
    for phase in data["phases"]:
        lines += [f"### Phase {phase['no']:02} — {phase['title']} ({phase['window']}; {phase['scope']})", "",
                  f"**Exit gate:** {phase['gate']}  ",
                  "**Prerequisites:** " + (", ".join(f"Phase {x:02}" for x in phase["depends"]) or "None"), ""]
        module = None
        for task in data["tasks"]:
            if not task["Phase"].startswith(f"{phase['no']:02} - "):
                continue
            if module != task["Module"]:
                module = task["Module"]
                lines += [f"#### {module}", ""]
            checked = "x" if task["Status"] == "Done" else " "
            lines += [f"- [{checked}] **{task['ID']}** {task['Task']}  ",
                      f"  **Done when:** {task['Acceptance criterion']}"]
            if task["Evidence link"]:
                lines += [f"  **Evidence:** {task['Evidence link']}"]
        lines += [""]
    return "\n".join(lines) + "\n"


def pilot_view(data):
    lines = ["## 12. First-release pilot and capacity plan", "",
             "Generated from the JSON `pilot` list. The first release is local, single-user, Chromium-only and limited to the bundled fixture. It includes one provider, reviewed tests, execution, and results with a screenshot. Public targets, Celery, multi-user accounts, AI bug triage, dashboards, and exports follow the pilot.", "",
             "Estimates below are provisional engineering hours, not measured throughput or calendar promises. Owner is an accountable role; the maintainer assigns a named person before work starts. Work in dependency order with one active package. Re-estimate after the foundation and after the first complete run.", "",
             "| ID | Work package | Dependencies | Owner | Hours | Status |", "|---|---|---|---|---|---|"]
    for task in data["pilot"]:
        lines += [f"| {task['ID']} | {task['Task']} | {', '.join(task['Depends on tasks']) or 'None'} | {task['Owner']} | {task['Estimate hours']} | {task['Status']} |"]
    lines += ["", f"Initial pilot estimate: **{sum(t['Estimate hours'] for t in data['pilot'])} engineering hours**, excluding full-MVP work and contingency. No release date is assigned until actual throughput is available.", "",
              "Pilot exit gate: every package is Done with evidence, all deterministic fixture checks pass, quality thresholds in `docs/QUALITY_GATES.md` pass, and a clean checkout reproduces the workflow. Full phase gates and the full-MVP acceptance checklist remain required for subsequent capabilities.", ""]
    return "\n".join(lines) + "\n"


def replace_section(text, start, end, rendered):
    return text[:text.index(start)] + rendered + text[text.index(end):]


def generated_views(data, plan):
    plan = replace_section(plan, "## 5.", "## 6.", backlog_view(data))
    plan = replace_section(plan, "## 12.", "## 13.", pilot_view(data))
    start = plan.index("| Phase | Name | Window |")
    end = plan.index("**Critical path:**", start)
    lines = ["| Phase | Name | Window | Prerequisites | Gate |", "|---|---|---|---|---|"]
    for phase in data["phases"]:
        lines += [f"| {phase['no']:02} | {phase['title']} | {phase['window']} | {', '.join(f'{x:02}' for x in phase['depends']) or 'None'} | {phase['gate']} |"]
    plan = plan[:start] + "\n".join(lines) + "\n\n" + plan[end:]
    return {ROOT / "BUGAI_MICROTASK_BACKLOG.csv": csv_view(data), ROOT / "BUGAI_IMPLEMENTATION_PLAN.md": plan}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads((ROOT / "BUGAI_BACKLOG.json").read_text(encoding="utf-8"))
    validate(data)
    views = generated_views(data, (ROOT / "BUGAI_IMPLEMENTATION_PLAN.md").read_text(encoding="utf-8"))
    drift = []
    for path, content in views.items():
        if args.write:
            path.write_text(content, encoding="utf-8", newline="\n")
        elif path.read_text(encoding="utf-8") != content:
            drift.append(path.name)
    if drift:
        raise SystemExit("Generated backlog drift: " + ", ".join(drift))
    print("Backlog references, dependencies, evidence, and generated views are consistent")


if __name__ == "__main__":
    main()
